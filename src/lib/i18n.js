const DICT = { en, vi }

export function makeT(lang) {
  return (key, vars) => {
    const str = DICT[lang]?.[key] ?? DICT.en[key] ?? key
    return vars ? str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : str
  }
}
